/** Поведенческие сигналы перед ставкой (FR-11, ОВ-5). */

/** Чем участник нажал кнопку. */
export const POINTER_KINDS = ['mouse', 'touch', 'pen', 'keyboard', 'unknown'] as const;
export type PointerKind = (typeof POINTER_KINDS)[number];

/**
 * Что клиент рассказывает о своём клике.
 *
 * Сырые координаты не передаются намеренно: траектория указателя — это данные
 * о человеке, а для проверки «двигался или нет» достаточно агрегатов. Меньше
 * данных на проводе — меньше данных, которые придётся защищать.
 */
export interface BehaviorSignals {
  /**
   * Событие пришло от настоящего устройства, а не из кода страницы.
   *
   * Браузер выставляет этот признак сам и подделать его из JavaScript нельзя:
   * `dispatchEvent` всегда даёт `false`. Это и есть «клик без фиксации
   * движения пальца» из ТЗ §3.2 в том виде, в каком его вообще можно
   * зафиксировать.
   */
  readonly trusted: boolean;
  /** Каким устройством нажали. */
  readonly kind: PointerKind;
  /** Событий указателя за секунду перед кликом. */
  readonly moves: number;
  /** Суммарная длина траектории в пикселях, округлённая. */
  readonly pathPx: number;
  /** Сколько мс указатель провёл над кнопкой до нажатия. */
  readonly dwellMs: number;
}
