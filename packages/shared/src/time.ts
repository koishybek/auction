/**
 * Серверное время.
 *
 * NFR-04: часы клиента не влияют на таймер торгов ни при каких обстоятельствах.
 * Клиент получает `timeRemainingMs`, а не абсолютный дедлайн, и не считает время сам.
 */

export interface ServerTimeReport {
  /** Стенные часы, мс от эпохи. Для отображения и аудита. */
  readonly serverTs: number;
  /**
   * Монотонное время, мс от эпохи. Никогда не уменьшается в пределах процесса,
   * даже если NTP переставил системные часы назад.
   *
   * Все интервалы (остаток таймера, длительность торгов) считаются по нему:
   * прыжок стенных часов на секунду назад посреди аукциона иначе воскресил бы
   * уже завершённые торги.
   */
  readonly monotonicMs: number;
  /** То же серверное время в ISO — чтобы не гадать о часовом поясе в логах. */
  readonly iso: string;
  /** Аптайм процесса в секундах: помогает отличить рестарт от рассинхрона часов. */
  readonly uptimeSec: number;
}
