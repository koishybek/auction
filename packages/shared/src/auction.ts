/**
 * Контракт торговой сессии между api, gateway и web.
 *
 * Ядро механики Smart Hammer 50s: шаг ровно +3 %, любая принятая ставка
 * возвращает таймер к 50 000 мс, 50 секунд тишины закрывают торги.
 */

/** Таймер Smart Hammer. Значение из ТЗ и не подлежит настройке через конфиг. */
export const SMART_HAMMER_TIMER_MS = 50_000;

/** Шаг ставки в процентах. Других шагов в системе нет. */
export const BID_STEP_PERCENT = 3;

export const SESSION_STATUSES = ['RUNNING', 'FROZEN', 'FINISHED'] as const;
export type SessionStatusValue = (typeof SESSION_STATUSES)[number];

/**
 * Почему ставка не принята. Один код на одно условие — клиент по нему решает,
 * что показать человеку и что предложить сделать дальше.
 *
 * Разделены на два класса не для порядка, а по природе: первые проверяются в
 * PostgreSQL до обращения к состоянию торгов и не зависят от гонки, вторые
 * решаются атомарно внутри Lua-скрипта и зависят от того, кто успел раньше.
 */
export const BID_DENY_CODES = [
  /** Нет верификации через eGov — доступа к деньгам нет (FR-03). */
  'EGOV_NOT_VERIFIED',
  /** Пользователь заблокирован администратором. */
  'USER_BLOCKED',
  /** Задаток 10 % не на спецсчёте (FR-12). */
  'NO_DEPOSIT',
  /** Продавец не участвует в торгах по собственному лоту. */
  'SELLER_OWN_LOT',
  /** Чаще одной ставки в 500 мс (FR-10). Мягкий отказ: можно повторить. */
  'RATE_LIMITED',
  /**
   * Поведение похоже на автоматическое (FR-11): нужна капча.
   *
   * Мягкий отказ, как и лимит частоты: человек проходит проверку и ставит
   * дальше. Блокировать по одной эвристике нельзя — цена ошибки здесь
   * несоразмерна, живой участник теряет лот из-за манеры кликать.
   */
  'CAPTCHA_REQUIRED',
] as const;
export type BidDenyCode = (typeof BID_DENY_CODES)[number];

export const BID_RACE_CODES = [
  /** По лоту торги не идут. */
  'NO_SESSION',
  /** Торги заморожены (SLA Freeze) или уже завершены. */
  'NOT_RUNNING',
  /** 50 секунд тишины истекли — ставки больше не принимаются. */
  'TIMER_EXPIRED',
  /** Участник уже держит последнюю ставку: перебивать себя нельзя. */
  'SELF_OUTBID',
  /** Присланная сумма не равна шагу на момент обработки (QA-04). */
  'PRICE_MISMATCH',
] as const;
export type BidRaceCode = (typeof BID_RACE_CODES)[number];

export type BidRejectCode = BidDenyCode | BidRaceCode;

/**
 * Снимок состояния торгов для клиента.
 *
 * Абсолютного дедлайна здесь нет намеренно: клиент получает остаток в
 * миллисекундах, а не момент времени (CLAUDE.md §4.3). Часы браузера не
 * участвуют ни в чём — иначе перевод системного времени на минуту назад
 * подарил бы участнику лишнюю минуту торгов.
 */
export interface AuctionStateView {
  readonly lotId: string;
  readonly sessionId: string;
  readonly status: SessionStatusValue;
  /** Текущая цена в целых тенге. Внутри системы — тиыны. */
  readonly currentPriceTenge: number;
  /**
   * Сумма следующей ставки. Считает сервер — и это не удобство, а требование
   * QA-04: он же её и сверяет. Считай её клиент, правило округления жило бы в
   * двух местах, и участник получал бы отказ на честно посчитанной сумме.
   */
  readonly nextBidTenge: number;
  /** Номер последней принятой ставки. 0 — ставок ещё не было. */
  readonly seq: number;
  /** Сколько осталось до закрытия торгов. Никогда не отрицательно. */
  readonly timeRemainingMs: number;
  /** Серверное время снимка, мс эпохи. Только для диагностики и логов. */
  readonly serverTs: number;
}
