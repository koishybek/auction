import { describe, expect, it } from 'vitest';

import { refBonusTiyn } from './ref-bonus.service';

/**
 * Доля партнёра — 2 % от победной цены (FR-19, ОВ-11).
 *
 * Считается в целых числах: множитель 0.02 не представим двоичной дробью
 * точно, и на суммах в десятки миллионов это уже расхождение в тенге.
 */
describe('T-043: расчёт Ref-Bonus', () => {
  it('два процента от цены, в целых тенге', () => {
    // 46 350 000 ₸ → 927 000 ₸
    expect(refBonusTiyn(4_635_000_000n)).toBe(92_700_000n);
    // 1 000 000 ₸ → 20 000 ₸
    expect(refBonusTiyn(100_000_000n)).toBe(2_000_000n);
  });

  it('результат всегда кратен тенге', () => {
    for (const priceTenge of [1_000_001n, 12_345_679n, 999_999n]) {
      const bonus = refBonusTiyn(priceTenge * 100n);
      // На провод уходят целые тенге: сумма, не кратная им, там непредставима.
      expect(bonus % 100n).toBe(0n);
    }
  });

  it('половина округляется к чётному — как у шага цены', () => {
    // 1 250 ₸ × 2 % = 25,0 ₸ ровно — половины нет, проверяем соседние случаи.
    // 2 025 ₸ × 2 % = 40,5 ₸ → 40 (чётное вниз).
    expect(refBonusTiyn(202_500n)).toBe(4_000n);
    // 2 075 ₸ × 2 % = 41,5 ₸ → 42 (нечётное вверх).
    expect(refBonusTiyn(207_500n)).toBe(4_200n);
  });

  it('нулевая цена даёт нулевую долю', () => {
    expect(refBonusTiyn(0n)).toBe(0n);
  });
});
