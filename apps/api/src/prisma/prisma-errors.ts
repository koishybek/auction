/**
 * Опознание ошибок PostgreSQL, на которые код реагирует осмысленно.
 *
 * В одном экземпляре, потому что «что такое P2002» — это правило, а не деталь
 * вызова: копии кода ошибки по файлам расходятся ровно тогда, когда меняется
 * версия Prisma, и расхождение выглядит как «иногда двойная запись проходит».
 */

/**
 * Нарушение уникального ключа.
 *
 * На этом коде держатся инварианты, которые гарантирует база, а не порядок
 * вызовов: один псевдоним на пару «участник + лот», одна запись на показ, одна
 * доплата на лот. Проигравшая гонку сторона не падает, а читает чужую запись.
 */
export function isUniqueViolation(error: unknown): boolean {
  return typeof error === 'object' && error !== null && 'code' in error && error.code === 'P2002';
}

/**
 * Неисправимая ошибка записи: повтор её не исправит.
 *
 * Отличать обязательно. Карантин — это признание «эта запись не запишется
 * никогда», и отправлять туда ставку из-за упавшей на секунду базы значит
 * своими руками выкидывать её из юридической записи: PostgreSQL перезапустился,
 * пул исчерпан, сеть моргнула — а ставки участников уехали разбираться руками.
 *
 * Признаём неисправимыми только ошибки о самих данных: нарушение внешнего
 * ключа (P2003) — ставка ссылается на лот или участника, которых нет; неверное
 * значение колонки (P2000, P2005, P2006); нарушение проверки (P2004). Всё
 * остальное — включая любые P1xxx о соединении — временное, и запись остаётся
 * ждать следующего захода.
 *
 * Уникальность (P2002) сюда не входит намеренно: повторная доставка одной и той
 * же ставки штатна, и её гасит `skipDuplicates`.
 */
const PERMANENT_WRITE_ERRORS = new Set(['P2000', 'P2003', 'P2004', 'P2005', 'P2006', 'P2011']);

export function isPermanentWriteError(error: unknown): boolean {
  if (typeof error !== 'object' || error === null || !('code' in error)) {
    return false;
  }
  const code = (error as { code?: unknown }).code;
  return typeof code === 'string' && PERMANENT_WRITE_ERRORS.has(code);
}
