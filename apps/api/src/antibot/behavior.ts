import type { BehaviorSignals } from '@auction/shared';

/**
 * Поведенческая эвристика ставки (T-049, FR-11, ОВ-5).
 *
 * ТЗ §3.2 требует ловить «клик без фиксации движения пальца/курсора». Чистая
 * функция без сети и базы: это правило, по которому живому человеку могут
 * отказать, и проверять его нужно таблицей случаев, а не наблюдением.
 *
 * Исход — не «бот/не бот», а «нужна ли проверка». Эвристика по одному клику не
 * отличит автомат от человека с трекпадом, и притворяться, что отличит, значит
 * терять участников на ровном месте.
 *
 * ГЛАВНЫЙ признак — доверенность события, а не длина траектории. Так вышло не
 * из удобства: тап по экрану телефона не даёт ни одного движения указателя
 * вовсе, и правило «нет траектории — значит бот» отправляло бы на капчу всех
 * мобильных участников. Проверено браузером: живой клик мышью, дошедший до
 * кнопки одним прыжком, тоже давал ноль движений.
 *
 * ЧЕГО ЭТО НЕ ЛОВИТ, и об этом нужно помнить. Сигналы приходят от клиента, а
 * клиент может быть не нашей страницей: тот, кто пишет в сокет напрямую,
 * пришлёт `trusted: true` и любые красивые цифры. Эвристика закрывает ровно
 * сценарий ТЗ §3.2 — автокликер и dispatchEvent на нашей же странице. Против
 * самописного бота работает не она, а капча и Cloudflare (T-050): барьер,
 * который клиент не заполняет сам.
 */

/** Меньше этого числа событий указателя — движения фактически не было. */
const MIN_MOVES = 3;

/** Меньше этого пути в пикселях — курсор стоял на месте. */
const MIN_PATH_PX = 12;

/**
 * Меньше этого времени над кнопкой — нажатие произошло раньше, чем человек
 * успел бы прицелиться. 40 мс — меньше одного кадра при 24 к/с.
 */
const MIN_DWELL_MS = 40;

export type BehaviorVerdict = 'HUMAN' | 'CHALLENGE';

export interface BehaviorAssessment {
  readonly verdict: BehaviorVerdict;
  /**
   * Что показалось необычным.
   *
   * При `CHALLENGE` — причина отказа. При `HUMAN` — мягкие наблюдения о
   * движении: они не влияют на решение, но пишутся в лог и однажды станут
   * основой для настройки порогов на боевой статистике.
   */
  readonly reasons: readonly string[];
}

/**
 * Оценить сигналы клика.
 *
 * Клавиатура и сенсор проходят по факту доверенного события. Для клавиатуры
 * это требование доступности: человек, который не пользуется мышью, обязан
 * участвовать наравне со всеми. Для сенсора — физика: у тапа нет траектории.
 *
 * Мышь — единственный случай, где траектория осмысленна: указатель, мгновенно
 * возникший на кнопке и нажавший без паузы, ведёт себя не как рука.
 */
export function assessBehavior(signals: BehaviorSignals | null): BehaviorAssessment {
  if (signals === null) {
    /**
     * Сигналов нет — клиент не наша страница.
     *
     * Это НЕ повод для капчи, хотя соблазн велик. Тот, кто пишет в сокет
     * напрямую, пришлёт любые сигналы, какие попросим, — а страдали бы от
     * требования честные не-браузерные клиенты: мобильное приложение,
     * нагрузочный стенд, служебные интеграции. Барьер для самописных ботов
     * ставится на входе (Cloudflare, T-050), а не здесь.
     */
    return { verdict: 'HUMAN', reasons: ['NO_SIGNALS'] };
  }
  if (!signals.trusted) {
    // Событие сгенерировано кодом страницы. Ровно сценарий ТЗ §3.2.
    return { verdict: 'CHALLENGE', reasons: ['UNTRUSTED_EVENT'] };
  }
  if (signals.kind !== 'mouse') {
    return { verdict: 'HUMAN', reasons: [] };
  }

  /**
   * Движения указателя СОБИРАЮТСЯ, но решения по ним не принимается.
   *
   * Так вышло по факту проверки в браузере, а не из осторожности. Любой порог
   * «мало движений — на капчу» отбивал живые клики: мышь, дошедшая до кнопки
   * одним прыжком, даёт ноль пройденного пути; быстрый человек нажимает
   * раньше сорока миллисекунд; тап вообще не двигается. Калибровать пороги не
   * на чем — боевого трафика ещё нет, — а угадывать здесь значит отнимать лот
   * у живого участника.
   *
   * Признаки возвращаются вызывающему: они пишутся рядом с решением и станут
   * основой для настройки, когда появится статистика настоящих торгов.
   */
  const soft: string[] = [];
  if (signals.moves < MIN_MOVES) {
    soft.push('FEW_POINTER_MOVES');
  }
  if (signals.pathPx < MIN_PATH_PX) {
    soft.push('SHORT_TRAJECTORY');
  }
  if (signals.dwellMs < MIN_DWELL_MS) {
    soft.push('FAST_CLICK');
  }
  return { verdict: 'HUMAN', reasons: soft };
}
