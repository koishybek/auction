/**
 * Общие куски Lua для скриптов торгов (T-024).
 *
 * Вынесены отдельно, потому что дублировать их нельзя: правило округления шага
 * существует в системе ровно в одном экземпляре. Две реализации «+3 %» — это
 * два ответа на вопрос, сколько человек должен заплатить.
 */

/**
 * Объявляет локальную `nowMs` — «сейчас» по часам Redis, в миллисекундах эпохи.
 *
 * Часы именно Redis: процессов много (API, gateway, воркеры), общих монотонных
 * часов у них нет, а сравнение с дедлайном обязано давать один ответ для всех.
 *
 * `string.format('%.0f')` при печати обязателен: `tostring(1786000000000)`
 * в Lua даёт «1.786e+12», и время превращается в мусор молча.
 */
export const NOW_MS_LUA = `
local t = redis.call('TIME')
local nowMs = t[1] * 1000 + math.floor(t[2] / 1000)
`;

/**
 * Объявляет функцию `nextPriceTiyn(price)` — шаг ставки.
 *
 * Ровно +3 % с банковским округлением (half-to-even) до целого тенге. Правило
 * зафиксировано планом (T-024) и не меняется без пересмотра плана. Следствие,
 * на которое опирается вся сериализация: цена всегда кратна 100 тиынам.
 *
 * Считается в целых числах, а не через умножение на 1.03: множитель 1.03 не
 * представим двоичной дробью точно, и на больших суммах ошибка вылезает в
 * последнем тенге. Здесь `tenge * 103` — точное целое, а деление на 100
 * разложено на частное и остаток, поэтому округление решается сравнением
 * остатка с 50, а не поведением плавающей точки.
 *
 * Граница точности: числа Lua — двойные, целые в них точны до 2^53 ≈ 9·10^15.
 * Верхняя цена лота ограничена триллионом тенге (10^14 тиын), запас ~90×.
 */
export const NEXT_PRICE_LUA = `
local function nextPriceTiyn(priceTiyn)
  local tenge = priceTiyn / 100
  local scaled = tenge * 103
  local q = math.floor(scaled / 100)
  local r = scaled - q * 100
  if r > 50 then
    q = q + 1
  elseif r == 50 and q % 2 == 1 then
    q = q + 1
  end
  return q * 100
end
`;
