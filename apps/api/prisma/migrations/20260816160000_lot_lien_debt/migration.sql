-- T-046: долг залогодержателю по объекту.
--
-- Нужен Payment Splitter'у: из доплаты победителя долг гасится на ссудный
-- счёт банка раньше, чем остаток уходит продавцу (ТЗ §5.2). Без суммы долга
-- расщепление посчитать нельзя.
--
-- NOT NULL с DEFAULT 0, а не nullable: «не в залоге» — это ноль, а не
-- «неизвестно». NULL здесь означал бы, что расщепление надо отложить до
-- выяснения, и такой лот молча завис бы между торгами и деньгами.
ALTER TABLE "lots" ADD COLUMN "lien_debt_tiyn" BIGINT NOT NULL DEFAULT 0;
