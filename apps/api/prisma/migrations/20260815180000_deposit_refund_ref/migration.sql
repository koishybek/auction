-- T-037: отметка о том, что поручение на возврат уже ушло в банк.
--
-- Нужна именно колонка в БД, а не ключ в Redis: по ней два воркера
-- договариваются, кто из них отправляет TRIGGER_REFUND, и договорённость
-- обязана пережить перезапуск. Задаток можно вернуть с опозданием, но нельзя
-- вернуть дважды.
--
-- Nullable без DEFAULT — так и задумано: NULL здесь означает «поручения не
-- было», и это осмысленное состояние, а не пропуск данных.
ALTER TABLE "deposits" ADD COLUMN "refund_ref" TEXT;

-- Выборка воркера: «что пора возвращать». Частичный индекс, потому что
-- интересны только неотправленные — остальные строки в него не попадают
-- и не раздувают его на всём объёме задатков.
CREATE INDEX "deposits_refund_pending_idx" ON "deposits" ("refund_deadline_at")
  WHERE "status" = 'REFUND_PENDING' AND "refund_ref" IS NULL;
