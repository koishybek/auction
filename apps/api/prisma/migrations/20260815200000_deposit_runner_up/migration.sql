-- T-038: сценарий Runner-Up (FR-14).
--
-- Одна колонка на оба шага сценария: сначала «до какого момента участник №2
-- выбирает опцию», потом «до какого момента держим его задаток по Опции А».
-- Две колонки на два шага одного сценария разошлись бы: заполнена была бы то
-- одна, то другая, и запрос «чей это задаток» пришлось бы писать через ИЛИ.
--
-- Непустое значение здесь и означает «это задаток участника №2»: отдельного
-- флага не нужно, а два признака одного факта неизбежно разъезжаются.
ALTER TABLE "deposits" ADD COLUMN "runner_up_until" TIMESTAMPTZ(3);

-- Выборка воркера: у кого истёк срок текущего шага.
CREATE INDEX "deposits_runner_up_idx" ON "deposits" ("runner_up_until")
  WHERE "runner_up_until" IS NOT NULL;
