-- T-057: одна доплата на лот — гарантией базы, а не порядком вызовов.
--
-- Раньше «одна доплата» держалась на связке «сначала findFirst, потом create».
-- Между чтением и записью есть окно: два подтверждения сделки, пришедшие
-- одновременно (двойной клик, повтор запроса, две реплики API), создают две
-- строки доплаты по одному лоту — то есть два счёта победителю на одну сделку.
--
-- Индекс уникальный и полный, без условия: доплата по лоту существует в одном
-- экземпляре в любом статусе. Отменённая доплата — это статус, а не вторая
-- строка.
CREATE UNIQUE INDEX "payments_lot_id_key" ON "payments" ("lot_id");

-- Ссылка выставленного счёта — отдельной колонкой, а не в bank_ref.
--
-- bank_ref уже занят: туда пишется идентификатор события оплаты из вебхука.
-- Две сущности в одной колонке означают, что вопрос «счёт вообще выставлен?»
-- нельзя задать базе: до оплаты колонка пуста, после — заполнена чужим
-- значением. А вопрос этот денежный: счёт мог не уйти в банк (сеть, таймаут),
-- и тогда победитель не получит ничего, а лот уже закрыт.
ALTER TABLE "payments" ADD COLUMN "invoice_ref" TEXT;
