-- T-042: один активный лид на объект.
--
-- Частичный уникальный индекс, а не проверка в коде: закрепление лида — это
-- деньги партнёра (2 % от победной цены), и два партнёра, закрепивших один
-- объект, — это спор о комиссии. Проверка «есть ли уже лид» между чтением и
-- записью оставляет окно, в которое пролезают оба; индекс окна не оставляет.
--
-- Только для LOCKED: истёкшие и сконвертированные лиды по одному объекту
-- накапливаются как история, и запрещать их нельзя.
CREATE UNIQUE INDEX "partner_leads_locked_object_key"
  ON "partner_leads" ("cadastre_or_vin")
  WHERE "status" = 'LOCKED';
