-- T-063: витрина лота — то, по чему человек выбирает объект.
--
-- До этого карточка знала о лоте три вещи: тип, кадастровый номер и цену.
-- Для торгового движка этого хватает — цену двигает шаг, а не описание, — но
-- каталог недвижимости из кадастровых номеров выбрать объект не позволяет: он
-- выглядит выгрузкой из реестра, а не витриной.
--
-- Все поля необязательные и заполняются продавцом при подаче. Обязательными их
-- делать нельзя: лот заводится до того, как собраны материалы, и пустая
-- карточка честнее отказа в подаче.
ALTER TABLE "lots"
  ADD COLUMN "title" TEXT,
  ADD COLUMN "address" TEXT,
  ADD COLUMN "description" TEXT,
  -- Площадь в сотых квадратного метра и пробег в километрах: целые числа, а не
  -- дробные. Дробь в характеристике объекта ведёт себя ровно так же, как дробь
  -- в деньгах, — округляется по-разному в разных местах.
  ADD COLUMN "area_sqm_x100" INTEGER,
  ADD COLUMN "mileage_km" INTEGER,
  ADD COLUMN "build_year" INTEGER;
