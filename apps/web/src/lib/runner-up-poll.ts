/**
 * Когда переспрашивать сервер о праве участника №2 (FR-14).
 *
 * Окно выбора открывается в момент `auction_finished`, и клиент сразу
 * спрашивает: «это я второй?». Ответа в этот момент может ещё не быть.
 * Событие о закрытии публикует атомарный скрипт в Redis, а метку участника №2
 * ставит воркер уже после — отдельной записью в PostgreSQL. Порядок такой не
 * случайно: сначала все узнают, что торги закончились, и только потом
 * разбираются последствия.
 *
 * Один вопрос поэтому ничего не гарантирует: пришедший на миллисекунду раньше
 * записи получает «не предлагали» и больше не спрашивает — человек теряет свой
 * выбор до перезагрузки страницы. Поймано прогоном CI, где сервер оказался
 * медленнее браузера; на машине разработчика порядок обратный, и дефекта не
 * видно.
 *
 * Отсюда правило: спрашивать несколько раз, но недолго и не бесконечно. Если
 * предложения нет — его и не будет: участников №2 на лоте ровно один.
 */

/** Пауза между вопросами. */
export const RUNNER_UP_RETRY_MS = 1_500;

/** Сколько всего вопросов задаём, включая первый. 10 × 1.5 с ≈ 15 с. */
export const RUNNER_UP_ATTEMPTS = 10;

/** Ответ сервера в той части, которая решает, спрашивать ли снова. */
export interface RunnerUpAnswer {
  readonly offered: boolean;
}

/**
 * Спрашивать ли ещё раз.
 *
 * `null` — ответа не было вовсе (сеть, 401 на госте): это не «не предлагали»,
 * и попытку стоит повторить.
 */
export function shouldAskAgain(answer: RunnerUpAnswer | null, attempts: number): boolean {
  if (answer?.offered === true) {
    return false;
  }
  return attempts < RUNNER_UP_ATTEMPTS;
}
